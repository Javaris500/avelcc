/**
 * STYLED FOR THIS SYSTEM, not left at shadcn defaults. Seven changes, each
 * pointing at a token rather than a value:
 *
 *   panel      rounded-lg, which is "windows, popovers, sheets" on our radius
 *              scale. shadcn's rounded-md is the CARD step and understates a
 *              floating surface.
 *   elevation  shadow-e2 with elevation-border-raised, so a menu is layered by
 *              lightness AND border, which is what makes flat surfaces read as
 *              raised without gradients.
 *   motion     zoom to 0.98 instead of 0.95. LOGO-BRIEF: "Nothing bouncy:
 *              overshoot reads as playful, and this brand is deliberate."
 *   items      rounded-xs, the chip step, with a real transition rather than an
 *              instant colour swap. cursor-pointer, because these ARE clickable
 *              and shadcn's cursor-default says otherwise.
 *   disabled   --opacity-disabled, not an invented 50%.
 *   labels     text-micro uppercase in text-subtle, matching the nav's group
 *              labels so a menu heading reads like every other heading.
 *   separator  the elevation border token, not bg-border.
 */
/**
 * shadcn's dropdown menu, audited at generation.
 *
 * Every `dark:` utility removed — this app has no `dark` class, it puts
 * `.light` on the shell wrapper with dark as the default, so those rules are
 * dead code that reads as though it works. Both themes resolve through the
 * token alias layer in tokens.css instead.
 *
 * Left as generated otherwise: the Radix behaviour is the reason to use this
 * at all — focus trapping, roving tabindex, typeahead, Escape to close, and
 * correct aria-expanded on the trigger. Reimplementing that by hand is how a
 * dropdown ends up unusable by keyboard.
 */
